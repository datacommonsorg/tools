"""Verifies the analytics golden fixture against the current code.

The fixture is regenerated by `regenerate_golden.py`, never by hand. When
this test fails, the figure that changed is either a bug to fix or a
deliberate change to regenerate and review in the JSON diff.
"""

import json
from pathlib import Path

import pytest

from narratives_agent.analytics.golden import regenerate_golden

_REQUIRED_CASES = (
    "timeseries_single_point",
    "timeseries_multi_decade_positive",
    "summary_multi_decade_positive",
    "timeseries_zero_start",
    "timeseries_negative_end",
    "timeseries_daily_change_under_a_year",
    "timeseries_mixed_precision",
    "timeseries_multi_place_shared_date",
    "timeseries_multi_place_disjoint_dates",
    "alignment_prefers_coverage_over_recency",
    "summary_cohort",
    "ranking_with_ties",
    "ranking_with_ties_ascending",
    "refusal_insufficient_coverage",
    "refusal_ranking_insufficient_coverage",
    "summary_empty_table",
    "refusal_empty_table_alignment",
    "refusal_empty_table_timeseries",
    "refusal_unit_mismatch",
    "refusal_scaling_mismatch",
    "compatible_units",
    "refusal_ranking_invalid_n",
    "digest",
    "digest_prompt",
)


def test_checked_in_fixture_matches_the_current_code() -> None:
    # Test: The golden fixture against the live implementation.
    # Situation: `core_golden.json` was written by `regenerate_golden.py`
    #   at the current commit.
    # Expectation: The file equals the current rendered output, so a
    #   failure shows a diff of the changed lines (in full with
    #   `pytest -vv`), and it holds exactly the required golden cases, each
    #   listed once.
    expected = regenerate_golden.GOLDEN_PATH.read_text(encoding="utf-8")
    actual = regenerate_golden.render_golden(
        regenerate_golden.build_golden_cases()
    )
    assert actual == expected
    assert len(_REQUIRED_CASES) == len(set(_REQUIRED_CASES))
    assert set(json.loads(expected)) == set(_REQUIRED_CASES)


def test_check_mode_reports_a_stale_fixture(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    # Test: The `--check` command-line mode on a stale fixture.
    # Situation: The fixture path points at a file whose content differs
    #   from the current output.
    # Expectation: `main(["--check"])` returns 1 without modifying the file.
    stale = tmp_path / "core_golden.json"
    stale.write_text("{}\n", encoding="utf-8")
    monkeypatch.setattr(regenerate_golden, "GOLDEN_PATH", stale)
    assert regenerate_golden.main(["--check"]) == 1
    assert stale.read_text(encoding="utf-8") == "{}\n"


def test_check_mode_reports_a_missing_fixture(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    # Test: The `--check` command-line mode without a fixture file.
    # Situation: The fixture path points at a file that does not exist.
    # Expectation: `main(["--check"])` returns 1 and does not create the
    #   file.
    missing = tmp_path / "core_golden.json"
    monkeypatch.setattr(regenerate_golden, "GOLDEN_PATH", missing)
    assert regenerate_golden.main(["--check"]) == 1
    assert not missing.exists()


def test_regeneration_writes_a_fixture_that_passes_the_check(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    # Test: The regeneration mode followed by the `--check` mode.
    # Situation: The fixture path points at a missing file.
    # Expectation: `main([])` writes the fixture and returns 0, the file
    #   holds the required golden cases, and `main(["--check"])` then
    #   returns 0.
    target = tmp_path / "core_golden.json"
    monkeypatch.setattr(regenerate_golden, "GOLDEN_PATH", target)
    assert regenerate_golden.main([]) == 0
    written = json.loads(target.read_text(encoding="utf-8"))
    assert set(written) == set(_REQUIRED_CASES)
    assert regenerate_golden.main(["--check"]) == 0
